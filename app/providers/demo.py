"""Deterministic, credential-free report writer.

Grilling is shared with the live adapter. This adapter only writes the brief,
and it writes it from the answers alone. It does not call Qloo or a model.
"""

from __future__ import annotations

from typing import List

from app.model import BusinessProfile, GrillTurn, Report
from app.providers.base import Provider
from app.providers.grilling import answers_report


class DemoProvider(Provider):
    name = "demo"

    def write_report(
        self,
        profile: BusinessProfile,
        opening: str,
        transcript: List[GrillTurn],
    ) -> Report:
        report = answers_report(profile, transcript)
        report.caveat = (
            "Draft generated by the VentureLens demo provider. Connect a real "
            "LLM and Qloo data before using it for decisions."
        )
        return report
